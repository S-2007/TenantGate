"""Self-service tenants and admin user management (Phase 6).

GET  /tenants/registration-info   public: is registration open, is a code needed
POST /tenants/register            public, rate-limited: new company + its first admin
GET  /admin/users                 admin: users of the caller's tenant (no password hashes)
POST /admin/users                 admin: create a user in the caller's tenant

Security rules:
- The new tenant id and admin user id are generated by the database, never by the client.
  The client can't choose roles for the first user either: it is always exactly ``admin``.
- ``register_tenant`` / ``admin_create_user`` (migration 0007) take an advisory lock and check
  the tenant cap / user quota in the same transaction as the insert, so concurrent requests
  can't race past the limits. They also write the audit row in that transaction.
- ``admin_create_user`` takes the tenant from the RLS context (the caller's verified identity),
  not from the request, so an admin can only ever add users to their own company.
- A duplicate slug or email gets one generic 409 that doesn't say which one collided.
"""

from __future__ import annotations

import datetime as dt
import hmac
import logging
import re
import uuid
from typing import Literal

from fastapi import APIRouter, Depends, HTTPException, Request, status
from fastapi.concurrency import run_in_threadpool
from pydantic import BaseModel, ConfigDict, Field, field_validator
from sqlalchemy import select

from app.admin.acl import AclChangeError, call_definer
from app.audit.api import require_admin
from app.auth.passwords import MAX_PASSWORD_CHARS, hash_password
from app.auth.policy import AuthUser
from app.auth.tokens import issue_access_token
from app.config import get_settings
from app.db.models import User
from app.db.session import transaction
from app.ratelimit import enforce

security_log = logging.getLogger("app.security")
router = APIRouter(tags=["tenants"])

# Roles an admin may hand out. 'contractor' is deliberately absent from self-service: a
# contractor is the "outsider" persona of the seed data; any role from KNOWN_ROLES still works
# through PATCH /admin/users/{id}/roles.
ASSIGNABLE_ROLES = ("admin", "employee", "engineering", "finance", "hr", "manager")
AssignableRole = Literal[ASSIGNABLE_ROLES]  # type: ignore[valid-type]

SLUG_RE = re.compile(r"^[a-z0-9](?:[a-z0-9-]{1,38}[a-z0-9])$")
EMAIL_RE = re.compile(r"^[^@\s<>\"']{1,64}@[A-Za-z0-9.-]{1,180}\.[A-Za-z]{2,24}$")
MIN_PASSWORD = 12
DUPLICATE = "a company with this slug, or a user with this email, already exists"


def _password(v: str) -> str:
    if len(v) < MIN_PASSWORD:
        raise ValueError(f"password must be at least {MIN_PASSWORD} characters")
    if v.strip() != v or len(set(v)) < 5:
        raise ValueError("password is too weak (no leading/trailing spaces, mix characters)")
    return v


def _email(v: str) -> str:
    v = v.strip().lower()
    if not EMAIL_RE.match(v):
        raise ValueError("not a valid email address")
    return v


class RegistrationInfo(BaseModel):
    enabled: bool
    code_required: bool
    assignable_roles: list[str]
    password_min_length: int


class RegisterRequest(BaseModel):
    """A new company and its first admin. No tenant id, user id or role can be supplied."""

    model_config = ConfigDict(extra="forbid")

    company_name: str = Field(min_length=2, max_length=80)
    slug: str = Field(min_length=3, max_length=40)
    admin_email: str = Field(min_length=6, max_length=254)
    admin_password: str = Field(min_length=1, max_length=MAX_PASSWORD_CHARS)
    registration_code: str = Field(default="", max_length=200)

    _pw = field_validator("admin_password")(classmethod(lambda cls, v: _password(v)))
    _em = field_validator("admin_email")(classmethod(lambda cls, v: _email(v)))

    @field_validator("slug")
    @classmethod
    def _slug(cls, v: str) -> str:
        v = v.strip().lower()
        if not SLUG_RE.match(v) or "--" in v:
            raise ValueError("slug: 3-40 of a-z, 0-9 and single '-', not at either end")
        return v

    @field_validator("company_name")
    @classmethod
    def _name(cls, v: str) -> str:
        v = " ".join(v.split())
        if any(ord(ch) < 32 for ch in v) or "<" in v or ">" in v:
            raise ValueError("company name contains characters that are not allowed")
        return v


class RegisterResponse(BaseModel):
    tenant_id: uuid.UUID
    user_id: uuid.UUID
    slug: str
    access_token: str
    token_type: str = "bearer"  # noqa: S105 - OAuth2 token type
    expires_in: int


class UserCreate(BaseModel):
    model_config = ConfigDict(extra="forbid")

    email: str = Field(min_length=6, max_length=254)
    roles: list[AssignableRole] = Field(min_length=1, max_length=len(ASSIGNABLE_ROLES))
    password: str = Field(min_length=1, max_length=MAX_PASSWORD_CHARS)

    _pw = field_validator("password")(classmethod(lambda cls, v: _password(v)))
    _em = field_validator("email")(classmethod(lambda cls, v: _email(v)))


class UserOut(BaseModel):
    id: uuid.UUID
    email: str
    roles: list[str]
    is_active: bool
    created_at: dt.datetime


def _http(exc: AclChangeError, *, conflict_msg: str | None = None) -> HTTPException:
    msg = conflict_msg if (exc.status == 409 and exc.message == "already exists") else exc.message
    return HTTPException(status_code=exc.status, detail=msg)


@router.get("/tenants/registration-info", response_model=RegistrationInfo)
def registration_info() -> RegistrationInfo:
    """What the register page needs to know. Says nothing about existing tenants."""
    s = get_settings()
    return RegistrationInfo(
        enabled=s.registration_enabled,
        code_required=bool(s.registration_code),
        assignable_roles=list(ASSIGNABLE_ROLES),
        password_min_length=MIN_PASSWORD,
    )


@router.post("/tenants/register", response_model=RegisterResponse, status_code=201)
async def register(body: RegisterRequest, request: Request) -> RegisterResponse:
    """Create a company and its first admin, and log that admin in."""
    s = get_settings()
    enforce(request, "register", s.register_rate_per_hour, 3600)
    if not s.registration_enabled:
        raise HTTPException(status.HTTP_403_FORBIDDEN, "registration is disabled")
    if s.registration_code and not hmac.compare_digest(
        body.registration_code.encode(), s.registration_code.encode()
    ):
        security_log.warning("register_rejected reason=bad_code ip=%s",
                             request.client.host if request.client else "?")  # fmt: skip
        raise HTTPException(status.HTTP_403_FORBIDDEN, "invalid registration code")
    pw_hash = await run_in_threadpool(hash_password, body.admin_password)
    try:
        out = await run_in_threadpool(
            call_definer,
            None,
            "SELECT register_tenant(:slug, :name, :email, :pw, :cap, CAST(:rid AS uuid))",
            {"slug": body.slug, "name": body.company_name, "email": body.admin_email,
             "pw": pw_hash, "cap": s.max_tenants, "rid": request.state.request_id},
        )  # fmt: skip
    except AclChangeError as exc:
        raise _http(exc, conflict_msg=DUPLICATE) from exc
    tenant_id, user_id = uuid.UUID(out["tenant_id"]), uuid.UUID(out["user_id"])
    security_log.info("tenant_registered tenant=%s admin=%s", tenant_id, user_id)
    token, ttl = issue_access_token(
        user_id=user_id, tenant_id=tenant_id, roles=["admin"], settings=s
    )
    return RegisterResponse(
        tenant_id=tenant_id, user_id=user_id, slug=body.slug, access_token=token, expires_in=ttl
    )


@router.get("/admin/users", response_model=list[UserOut])
def list_users(admin: AuthUser = Depends(require_admin)) -> list[UserOut]:  # noqa: B008
    """Users of the caller's tenant only (explicit tenant WHERE; never the password hash)."""
    with transaction() as s:
        rows = s.execute(
            select(User.id, User.email, User.roles, User.is_active, User.created_at)
            .where(User.tenant_id == admin.tenant_id)
            .order_by(User.created_at, User.email)
        ).all()
    return [
        UserOut(
            id=r.id,
            email=r.email,
            roles=sorted(r.roles),
            is_active=r.is_active,
            created_at=r.created_at,
        )  # fmt: skip
        for r in rows
    ]


@router.post("/admin/users", response_model=UserOut, status_code=201)
async def create_user(
    body: UserCreate,
    request: Request,
    admin: AuthUser = Depends(require_admin),  # noqa: B008
) -> UserOut:
    """Add a user to the caller's company. The database re-checks admin + quota."""
    s = get_settings()
    pw_hash = await run_in_threadpool(hash_password, body.password)
    try:
        out = await run_in_threadpool(
            call_definer,
            admin,
            "SELECT admin_create_user(:email, CAST(:roles AS text[]), :pw, :cap, "
            "CAST(:rid AS uuid))",
            {"email": body.email, "roles": list(body.roles), "pw": pw_hash,
             "cap": s.max_users_per_tenant, "rid": request.state.request_id},
        )  # fmt: skip
    except AclChangeError as exc:
        raise _http(exc, conflict_msg="a user with this email already exists") from exc
    return UserOut(
        id=uuid.UUID(out["user_id"]),
        email=body.email,
        roles=list(out["roles"]),
        is_active=True,
        created_at=dt.datetime.now(dt.UTC),
    )
